// Single Source of Truth for Interactive Planet Navigation Sequence
export const PORTFOLIO_PLANETS: CelestialBody[] = CELESTIAL_BODIES.filter((p) => p.id > 0);

export function getAdjacentPlanets(currentId: number): {
  prev: CelestialBody;
  next: CelestialBody;
  currentIndex: number;
  totalPlanets: number;
} {
  const list = PORTFOLIO_PLANETS;
  const idx = list.findIndex((p) => p.id === currentId);
  const safeIdx = idx === -1 ? 0 : idx;
  const prevIdx = (safeIdx - 1 + list.length) % list.length;
  const nextIdx = (safeIdx + 1) % list.length;

  return {
    prev: list[prevIdx],
    next: list[nextIdx],
    currentIndex: safeIdx + 1,
    totalPlanets: list.length,
  };
}
